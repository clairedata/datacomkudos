-- 1. Enforce foreign key constraints in SQLite
PRAGMA foreign_keys = ON;

-- ============================================================================
-- TABLE: users
-- ROLE: Stores Datacom employees and authorization roles
-- ============================================================================
CREATE TABLE IF NOT EXISTS users (
    -- Unique employee identifier (UUID or company employee ID)
    id TEXT PRIMARY KEY,
    
    -- Full employee name (e.g., "Alice Martin")
    name TEXT NOT NULL,
    
    -- Unique corporate email address
    email TEXT NOT NULL UNIQUE,
    
    -- Access role: 'user' (standard employee) or 'admin' (moderator / people & culture)
    role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('user', 'admin')),
    
    -- Employee avatar URL
    avatar TEXT NOT NULL,
    
    -- Business unit or department (e.g., "Cloud Solutions", "Software Engineering")
    department TEXT NOT NULL,
    
    -- Account status: 1 = active (eligible to receive kudos), 0 = inactive
    is_active INTEGER NOT NULL DEFAULT 1 CHECK(is_active IN (0, 1)),
    
    -- Account creation timestamp
    created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- ============================================================================
-- TABLE: kudos
-- ROLE: Stores appreciation messages between colleagues
-- COMPLIANCE: Carries current moderation state columns required by brief (REQ-SUJET-06)
--             (is_visible, moderated_by, moderated_at, reason_for_moderation)
-- ============================================================================
CREATE TABLE IF NOT EXISTS kudos (
    -- Unique kudo identifier
    id TEXT PRIMARY KEY,
    
    -- Foreign key referencing the sender (employee giving the kudo)
    sender_id TEXT NOT NULL,
    
    -- Foreign key referencing the recipient (colleague being appreciated)
    recipient_id TEXT NOT NULL,
    
    -- Closed appreciation category list (strictly enforced via rule BR-03)
    category TEXT NOT NULL CHECK(category IN ('Teamwork', 'Innovation', 'Customer Delight', 'Leadership', 'Above & Beyond')),
    
    -- Text content of appreciation (between 3 and 500 characters per rule BR-04)
    message TEXT NOT NULL CHECK(length(trim(message)) >= 3 AND length(message) <= 500),
    
    -- Public feed visibility: 1 = visible to all, 0 = hidden by moderator
    is_visible INTEGER NOT NULL DEFAULT 1 CHECK(is_visible IN (0, 1)),
    
    -- User ID of the administrator who moderated the post (nullable)
    moderated_by TEXT,
    
    -- Timestamp when moderation occurred (ISO 8601, nullable)
    moderated_at TEXT,
    
    -- Mandatory reason recorded when hiding or reviewing a post (nullable)
    reason_for_moderation TEXT,
    
    -- Automated AI triage indicator: 1 = flagged for review, 0 = clean
    ai_flagged INTEGER NOT NULL DEFAULT 0 CHECK(ai_flagged IN (0, 1)),
    
    -- Explanation rationale generated by the AI detection engine (nullable)
    ai_flag_reason TEXT,
    
    -- Timestamp when the kudo was submitted
    created_at TEXT NOT NULL DEFAULT (datetime('now')),
    
    -- Timestamp when the kudo record was last updated
    updated_at TEXT NOT NULL DEFAULT (datetime('now')),
    
    -- Referential integrity constraints
    FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE RESTRICT,
    FOREIGN KEY (recipient_id) REFERENCES users(id) ON DELETE RESTRICT,
    FOREIGN KEY (moderated_by) REFERENCES users(id) ON DELETE SET NULL,
    
    -- Business rule BR-01: An employee cannot send kudos to themselves
    CHECK (sender_id != recipient_id)
);

-- ============================================================================
-- TABLE: moderation_audit_logs
-- ROLE: Immutable append-only audit trail logging every administrative action
-- ============================================================================
CREATE TABLE IF NOT EXISTS moderation_audit_logs (
    -- Unique audit log entry identifier
    id TEXT PRIMARY KEY,
    
    -- Identifier of the associated kudo
    kudo_id TEXT NOT NULL,
    
    -- Identifier of the administrator performing the action
    moderator_id TEXT NOT NULL,
    
    -- Action performed: HIDE, RESTORE, DELETE, or DISMISS_AI_FLAG
    action TEXT NOT NULL CHECK(action IN ('HIDE', 'RESTORE', 'DELETE', 'DISMISS_AI_FLAG')),
    
    -- Mandatory textual reason justifying the administrative action
    reason TEXT NOT NULL,
    
    -- Visibility state prior to the action (0 or 1, nullable for DELETE or DISMISS)
    previous_visibility INTEGER CHECK(previous_visibility IN (0, 1)),
    
    -- Visibility state after the action
    new_visibility INTEGER CHECK(new_visibility IN (0, 1)),
    
    -- Timestamp of the moderation action
    created_at TEXT NOT NULL DEFAULT (datetime('now')),
    
    -- Foreign key referencing the moderator
    FOREIGN KEY (moderator_id) REFERENCES users(id) ON DELETE RESTRICT
);

-- ============================================================================
-- SQL TRIGGERS FOR AUDIT LOG IMMUTABILITY
-- ROLE: Enforces strict append-only compliance; updates and deletes are aborted
-- ============================================================================
CREATE TRIGGER IF NOT EXISTS trg_prevent_audit_update
BEFORE UPDATE ON moderation_audit_logs
BEGIN
    SELECT RAISE(ABORT, 'Security Violation: Moderation audit log records are immutable and cannot be modified.');
END;

CREATE TRIGGER IF NOT EXISTS trg_prevent_audit_delete
BEFORE DELETE ON moderation_audit_logs
BEGIN
    SELECT RAISE(ABORT, 'Security Violation: Moderation audit log records are immutable and cannot be deleted.');
END;

-- ============================================================================
-- PERFORMANCE INDEXES
-- ============================================================================
-- Composite index for rapid loading of chronological public feed
CREATE INDEX IF NOT EXISTS idx_kudos_feed ON kudos(is_visible, created_at DESC);

-- Index for querying kudos received by a specific employee
CREATE INDEX IF NOT EXISTS idx_kudos_recipient ON kudos(recipient_id);

-- Index for administrator filter on AI-flagged messages
CREATE INDEX IF NOT EXISTS idx_kudos_ai_flagged ON kudos(ai_flagged);

-- Index for retrieving the audit trail of a specific kudo
CREATE INDEX IF NOT EXISTS idx_audit_kudo ON moderation_audit_logs(kudo_id);
